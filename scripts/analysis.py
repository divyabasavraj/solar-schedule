"""Milestone 5: the decision analysis, from the walk-forward backtest.

    uv run python scripts/analysis.py

Reads data/derived/backtest_lead{1,2}.parquet and writes
  docs/ANALYSIS.md             all tables (generated, do not edit)
  docs/figures/*.png           one chart per analysis
  data/derived/headline.json   the numbers quoted in README, memo and PLAN

Base case: lead-2 forecasts (always issued before the gate), notified rules
on the final X path, contract rate Rs 2.82/kWh.
"""

import json

import numpy as np
import pandas as pd

from solarschedule import charts, decide
from solarschedule.loss import pool, settle
from solarschedule.plant import CAPACITY_MW
from solarschedule.rules import CERC_2014, CERC_2024_PRE_APR2026, solar_regime_for_fy
from solarschedule.store import DATA, ROOT

OUT = DATA / "derived"
FIG = ROOT / "docs" / "figures"
FYS = list(range(2026, 2032))
QS = [f"q{q}" for q in (10, 20, 30, 40, 50, 60, 70, 80, 90)]
SELECT_END = "2025-07-01"  # optimiser picks percentiles on days before, is scored after
SEASONS = ["winter", "summer", "monsoon", "post-monsoon"]
LADDER = {"persistence": "Persistence", "cloud": "Clear-sky x cloud",
          "nwp_mean": "NWP → plant (free)", "q50": "GBM median", "opt": "GBM + optimiser"}


def fy_label(fy: int) -> str:
    return f"FY{fy % 100}-{(fy + 1) % 100:02d}"


def regimes(path: str = "final") -> dict:
    return {fy: solar_regime_for_fy(fy, path) for fy in FYS}


def optimise(res: pd.DataFrame, regs: dict) -> tuple[pd.DataFrame, dict]:
    """Pick the loss-minimising percentile per FY rule and season on the
    selection period; return chosen table and an `opt_<fy>` schedule column
    per FY (applied to every day; scored only after SELECT_END)."""
    sel = res[res.day < SELECT_END]
    rows, cols = [], {}
    for fy, reg in regs.items():
        sched = res.q50.copy()
        for season in SEASONS:
            part = sel[sel.season == season]
            best, _ = decide.best_quantile(part, reg, QS)
            mask = res.season == season
            sched[mask] = res.loc[mask, best]
            rows.append({"FY": fy_label(fy), "season": season, "percentile": best})
        cols[fy] = sched
    return pd.DataFrame(rows), cols


def main() -> None:
    res = pd.read_parquet(OUT / "backtest_lead2.parquet")
    lead1 = pd.read_parquet(OUT / "backtest_lead1.parquet")
    regs = regimes()
    choice, opt = optimise(res, regs)
    test = res.day >= SELECT_END
    md = ["# Decision analysis (generated by scripts/analysis.py; do not edit)", "",
          f"Base case: lead-2 forecasts, {res.day.nunique()} days ({res.day.min():%d %b %Y} – {res.day.max():%d %b %Y}), "
          f"notified rules on the final X path, contract rate ₹{decide.CONTRACT_RATE}/kWh. "
          "All ₹ figures are lakh per year for the 100 MW plant, scaled from the backtest days to 365. "
          f"The optimiser picks percentiles on days before {SELECT_END[:7]} and is scored on the days after; "
          "rows marked *out-of-sample* compare every model on those later days only.", ""]
    head = {}

    # 1. cost now and to 2031 -------------------------------------------------
    r_test = res[test].reset_index(drop=True)
    rows = []
    for fy, reg in regs.items():
        row = {"FY": fy_label(fy), "X %": reg.x_pct}
        for m in ("nwp_mean", "q50"):
            row[LADDER[m]] = decide.annual_loss_lakh(r_test, r_test[m], reg)
        row[LADDER["opt"]] = decide.annual_loss_lakh(r_test, opt[fy][test].to_numpy(), reg)
        q1, _ = decide.best_quantile(res[~test], reg, QS)  # one percentile, chosen on the selection period
        row["GBM + one percentile"] = decide.annual_loss_lakh(r_test, r_test[q1], reg)
        row["percentile"] = q1
        rows.append(row)
    pre = {"FY": "FY25-26 (old bands)", "X %": 100.0}
    for m in ("nwp_mean", "q50"):
        pre[LADDER[m]] = decide.annual_loss_lakh(r_test, r_test[m], CERC_2024_PRE_APR2026)
    pre[LADDER["opt"]] = pre["GBM + one percentile"] = np.nan
    pre["percentile"] = ""
    cost = pd.DataFrame([pre] + rows).round(1)
    md += ["## 1. Cost now and to 2031 (out-of-sample)", "",
           "Optimiser columns: a percentile per season, or one percentile all year, both chosen on the "
           "selection period for each year's rules.", "", cost.to_markdown(index=False), ""]
    c26, c31 = cost.iloc[1], cost.iloc[-1]
    head |= {
        "A_loss_fy27_free_nwp": c26[LADDER["nwp_mean"]],
        "B_loss_fy27_model_opt": c26[LADDER["opt"]],
        "C_loss_fy32_free_nwp": c31[LADDER["nwp_mean"]],
        "C_loss_fy32_model_opt": c31[LADDER["opt"]],
        "D_cut_fy27_pct": round((1 - c26[LADDER["opt"]] / c26[LADDER["nwp_mean"]]) * 100, 1),
        "D_cut_fy32_pct": round((1 - c31[LADDER["opt"]] / c31[LADDER["nwp_mean"]]) * 100, 1),
        "loss_fy26_old_bands_model": pre["GBM median"],
        "loss_one_percentile": dict(zip(cost.FY[1:], cost["GBM + one percentile"][1:])),
        "one_percentile": dict(zip(cost.FY[1:], cost.percentile[1:])),
        "revenue_lakh_per_year": round(float(r_test.actual.mean() * 8760 * 1000 * decide.CONTRACT_RATE / 1e5), 0),
    }
    fig, ax = charts.figure()
    x = np.arange(len(cost))
    for i, m in enumerate(["nwp_mean", "q50", "opt"]):
        ax.plot(x, cost[LADDER[m]], marker="o", ms=5, lw=2, color=charts.SERIES[i], label=LADDER[m])
        if m != "q50":  # the median and optimiser end within a few lakh: label one
            ax.annotate(f"{cost[LADDER[m]].iloc[-1]:.0f}", (x[-1], cost[LADDER[m]].iloc[-1]),
                        xytext=(8, 0), textcoords="offset points", va="center", fontsize=9, color=charts.INK_2)
    ax.set_xticks(x, [f"{f.split(' ')[0]}\nX={v:.0f}%" for f, v in zip(cost.FY, cost["X %"])])
    ax.set_ylabel("₹ lakh per year", color=charts.INK_2)
    ax.set_ylim(bottom=0)
    ax.legend(frameon=False, fontsize=9, loc="upper left")
    charts.title(ax, "Deviation losses grow every year the rules tighten",
                 "100 MW Pavagada, same forecast quality each year, contract rate ₹2.82/kWh")
    charts.save(fig, FIG / "cost_to_2031.png")

    # 2. schedule optimiser ---------------------------------------------------
    piv = choice.pivot(index="FY", columns="season", values="percentile")[SEASONS]
    md += ["## 2. Schedule optimiser: loss-minimising percentile, chosen on Jul 2024 – Jun 2025", "",
           piv.reset_index().to_markdown(index=False), ""]
    pct_rows = []
    for fy in (2026, 2031):
        _, losses = decide.best_quantile(r_test, regs[fy], QS)
        pct_rows.append({"FY": fy_label(fy)} | {q: round(v, 1) for q, v in losses.items()})
    md += ["Loss by single year-round percentile, out-of-sample:", "",
           pd.DataFrame(pct_rows).to_markdown(index=False), ""]
    fig, ax = charts.figure()
    for i, row in enumerate(pct_rows):
        vals = [row[q] for q in QS]
        ax.plot(range(len(QS)), vals, marker="o", ms=5, lw=2, color=charts.SERIES[i], label=row["FY"] + " rules")
        k = int(np.argmin(vals))
        ax.annotate(f"best {QS[k]}", (k, vals[k]), xytext=(0, -16), textcoords="offset points",
                    ha="center", fontsize=9, color=charts.INK_2)
    ax.set_xticks(range(len(QS)), [q.replace("q", "P") for q in QS])
    ax.set_xlabel("Forecast percentile promised to the grid", color=charts.INK_2)
    ax.set_ylabel("₹ lakh per year", color=charts.INK_2)
    ax.set_ylim(bottom=0)
    ax.legend(frameon=False, fontsize=9)
    charts.title(ax, "As X falls, the cheapest promise moves above the median",
                 "Annual loss for each percentile used all year, out-of-sample days")
    charts.save(fig, FIG / "optimiser.png")

    # 3. where the money goes ---------------------------------------------------
    hour = ((r_test.block // 4)).rename("hour")
    share = {}
    for fy in (2026, 2031):
        bl = decide.block_loss(r_test, opt[fy][test].to_numpy(), regs[fy])
        share[fy_label(fy)] = bl.groupby(hour).sum() / bl.sum() * 100
        low = opt[fy][test].to_numpy() < 20
        head[f"low_block_loss_share_{fy}"] = round(float(bl[low].sum() / bl.sum() * 100), 1)
        head[f"low_block_energy_share_{fy}"] = round(float(r_test.actual[low].sum() / r_test.actual.sum() * 100), 1)
        by_season = bl.groupby(r_test.season).sum() / bl.sum() * 100
        head[f"season_share_{fy}"] = by_season.round(1).to_dict()
    sh = pd.DataFrame(share).loc[5:19].round(1)
    shoulders = list(range(5, 9)) + list(range(15, 20))  # before 09:00 and from 15:00
    sh_share = {fy: round(float(pd.DataFrame(share)[fy].loc[shoulders].sum()), 1) for fy in share}
    head["shoulder_loss_share"] = sh_share
    md += ["## 3. Where the money goes (share of annual loss, %, GBM + optimiser)", "",
           "By hour of day (IST, block start):", "", sh.reset_index().to_markdown(index=False), "",
           "Shoulder hours (before 09:00 and from 15:00): "
           + "; ".join(f"{v}% of loss under {k} rules" for k, v in sh_share.items()) + ".", "",
           f"Blocks scheduled below 20 MW: {head['low_block_energy_share_2026']}% of energy, "
           f"{head['low_block_loss_share_2026']}% of loss in FY26-27; "
           f"{head['low_block_loss_share_2031']}% of loss in FY31-32.", "",
           "By season: " + "; ".join(f"{k}: {v}" for k, v in head["season_share_2031"].items()) + " (FY31-32).", ""]
    fig, ax = charts.figure()
    w = 0.38
    for i, fy in enumerate(sh.columns):
        ax.bar(sh.index + (i - 0.5) * w, sh[fy], width=w - 0.04, color=charts.SERIES[i], label=fy + " rules")
    ax.set_xticks(sh.index, [f"{h:02d}" for h in sh.index])
    ax.set_xlabel("Hour of day (IST)", color=charts.INK_2)
    ax.set_ylabel("% of annual loss", color=charts.INK_2)
    ax.legend(frameon=False, fontsize=9)
    a, b = sh_share.values()
    charts.title(ax, f"At X = 0 the shoulder hours' share of loss goes from {a:.0f}% to {b:.0f}%",
                 "Share of annual deviation loss by hour, GBM + optimiser schedule; midday still costs most")
    charts.save(fig, FIG / "where_money_goes.png")

    # 4. build vs buy -------------------------------------------------------------
    ladder = []
    for m in ("persistence", "cloud", "nwp_mean", "q50"):
        ladder.append({"model": LADDER[m]} | {fy_label(fy): decide.annual_loss_lakh(r_test, r_test[m], regs[fy])
                                               for fy in (2026, 2028, 2031)})
    ladder.append({"model": LADDER["opt"]} | {fy_label(fy): decide.annual_loss_lakh(r_test, opt[fy][test].to_numpy(), regs[fy])
                                              for fy in (2026, 2028, 2031)})
    lad = pd.DataFrame(ladder).round(1)
    def fee_ceiling(saved_lakh: float) -> float:  # Rs per MW per month
        return saved_lakh * 1e5 / CAPACITY_MW / 12

    qca = []
    for cut in (5, 10, 20, 30):
        row = {"error cut vs our model": f"{cut}%"}
        for fy in (2026, 2031):
            saved = decide.qca_saving(r_test, opt[fy][test], regs[fy], cut / 100)
            row[f"saved {fy_label(fy)}, ₹ lakh/yr"] = round(saved, 1)
            row[f"max QCA fee {fy_label(fy)}, ₹/MW/month"] = round(fee_ceiling(saved), -1)
        qca.append(row)
    qca = pd.DataFrame(qca)
    fee = decide.QCA_FEE_RS_PER_MW_MONTH
    w = {fy: decide.qca_breakeven_cut(r_test, opt[fy][test], regs[fy]) * 100 for fy in FYS}
    head["qca_fee_ceiling_10pct_fy27"] = float(qca.iloc[1, 2])
    head["qca_fee_ceiling_10pct_fy32"] = float(qca.iloc[1, 4])
    head["qca_fee_rs_per_mw_month"] = fee
    head["W_qca_breakeven_cut_pct"] = {fy_label(fy): round(v, 1) for fy, v in w.items()}
    md += ["## 4. Build vs buy", "", "Annual loss by forecasting step (out-of-sample):", "",
           lad.to_markdown(index=False), "",
           "What a QCA is worth if its error is X% smaller than ours (schedule moved that much closer to actual "
           "in every block). The fee ceiling is the saving per MW per month; a QCA charging more is not worth it:", "",
           qca.to_markdown(index=False), "",
           f"**Break-even (W):** at ₹{fee:,}/MW/month (GSECL's 2021 QCA tender estimate, the only public per-MW "
           "figure), a QCA must cut our error by "
           + "; ".join(f"{v:.0f}% ({k})" for k, v in head["W_qca_breakeven_cut_pct"].items())
           + ". The bar falls as X falls, because each MWh of error costs more.", ""]
    cuts = np.linspace(0, 0.4, 17)
    fig, ax = charts.figure()
    for i, fy in enumerate((2026, 2031)):
        s = opt[fy][test]
        ax.plot(cuts * 100, [fee_ceiling(decide.qca_saving(r_test, s, regs[fy], c)) for c in cuts],
                lw=2, color=charts.SERIES[i], label=fy_label(fy) + " rules")
        ax.plot(w[fy], fee, "o", ms=6, color=charts.SERIES[i])
        ax.annotate(f"W = {w[fy]:.0f}%", (w[fy], fee), xytext=(-8, 8) if i else (8, -14), textcoords="offset points",
                    ha="right" if i else "left", fontsize=9, color=charts.INK_2)
    ax.axhline(fee, color=charts.MUTED, lw=1, ls="--")
    ax.text(39.5, fee, f"QCA fee ₹{fee:,}/MW/month (GSECL 2021 tender)", fontsize=8, color=charts.INK_2,
            va="bottom", ha="right")
    ax.set_xlabel("QCA error, % smaller than ours", color=charts.INK_2)
    ax.set_ylabel("Fee the saving pays for, ₹/MW/month", color=charts.INK_2)
    ax.set_ylim(bottom=0)
    ax.set_xlim(0, 40)
    ax.legend(frameon=False, fontsize=9, loc="upper left")
    charts.title(ax, "A QCA pays only if it beats our model's error by about a tenth",
                 "What a better forecast is worth per MW per month, GBM + optimiser as the baseline")
    charts.save(fig, FIG / "build_vs_buy.png")

    # 5. battery ----------------------------------------------------------------------
    brows = []
    for e in (5, 10, 20):
        lo, hi = decide.bess_cost_lakh_per_year(e)
        row = {"battery": f"{e} MWh / {e / decide.BESS_HOURS:g} MW"}
        for fy in FYS:
            s = opt[fy][test].to_numpy()
            exp, lost = decide.battery(r_test.actual, s, regs[fy], e)
            after = decide.annual_loss_lakh(r_test.assign(actual=exp), s, regs[fy])
            lost_lakh = lost / r_test.day.nunique() * 365 * 1000 * decide.CONTRACT_RATE / 1e5
            base = decide.annual_loss_lakh(r_test, s, regs[fy])
            row[fy_label(fy)] = round(base - after - lost_lakh, 1)
        row["lease cost ₹ lakh/yr"] = f"{lo:.0f}–{hi:.0f}"
        pays = [fy_label(fy) for fy in FYS if row[fy_label(fy)] >= lo]
        row["first FY savings ≥ low cost"] = pays[0] if pays else "not by FY31-32"
        mw = e / decide.BESS_HOURS
        row["break-even lease FY31-32, ₹ lakh/MW/month"] = round(row[fy_label(FYS[-1])] / (mw * 12), 2)
        brows.append(row)
    bat = pd.DataFrame(brows)
    head["battery"] = bat.to_dict(orient="records")
    ten = brows[1]
    head["M_battery_10mwh_payback"] = ten["first FY savings ≥ low cost"]
    head["battery_10mwh_breakeven_lease"] = ten["break-even lease FY31-32, ₹ lakh/MW/month"]
    md += ["## 5. Battery that absorbs deviations", "",
           f"Net ₹ lakh/yr avoided (loss avoided minus energy lost at {decide.ROUND_TRIP:.0%} round trip), "
           "2-hour battery behind the meter, GBM + optimiser schedule. Cost: annual lease at standalone-BESS tender "
           f"tariffs of ₹{decide.BESS_RS_LAKH_PER_MW_MONTH[0]}–{decide.BESS_RS_LAKH_PER_MW_MONTH[1]} lakh/MW/month. "
           "The battery earns nothing else here (no arbitrage), so this is the deviation case alone.", "",
           bat.to_markdown(index=False), "",
           "**Payback (M):** the 10 MWh battery "
           + ("does not pay back by FY31-32" if ten["first FY savings ≥ low cost"].startswith("not")
              else f"pays back from {ten['first FY savings ≥ low cost']}") + ". Even at X = 0 it "
           f"covers its lease only if storage falls to ₹{ten['break-even lease FY31-32, ₹ lakh/MW/month']} lakh/MW/month, "
           f"about {ten['break-even lease FY31-32, ₹ lakh/MW/month'] / decide.BESS_RS_LAKH_PER_MW_MONTH[0]:.0%} of "
           "today's lowest tender. It needs a second income (arbitrage, ancillary services) to make sense.", ""]
    fig, ax = charts.figure()
    for i, row in enumerate(brows):
        vals = [row[fy_label(fy)] for fy in FYS]
        ax.plot(range(len(FYS)), vals, marker="o", ms=5, lw=2, color=charts.SERIES[i], label=row["battery"] + " saving")
        lo, hi = decide.bess_cost_lakh_per_year([5, 10, 20][i])
        ax.axhspan(lo, hi, color=charts.SERIES[i], alpha=0.10, lw=0)
        ax.text(len(FYS) - 0.6, (lo + hi) / 2, f"{[5, 10, 20][i]} MWh lease", fontsize=8,
                color=charts.INK_2, va="center")
    ax.set_xticks(range(len(FYS)), [fy_label(fy) for fy in FYS])
    ax.set_xlim(-0.3, len(FYS) + 0.5)
    ax.set_ylabel("₹ lakh per year", color=charts.INK_2)
    ax.set_ylim(bottom=0)
    ax.legend(frameon=False, fontsize=9, loc="upper left")
    charts.title(ax, "A deviation-only battery does not cover its lease",
                 "Net loss avoided per year vs annual lease cost band (shaded)")
    charts.save(fig, FIG / "battery.png")

    # 6. aggregation ------------------------------------------------------------------------
    nb_path = OUT / "backtest_neighbour_lead2.parquet"
    if nb_path.exists():
        nb = pd.read_parquet(nb_path)[["time_ist", "actual", "q50"]]
        both = r_test.merge(nb, on="time_ist", suffixes=("", "_n"))
        both = both[both.groupby("day").time_ist.transform("size") == 96].reset_index(drop=True)
        arow = []
        for fy in (2026, 2028, 2031):
            alone = (decide.annual_loss_lakh(both, both.q50, regs[fy])
                     + decide.annual_loss_lakh(both.assign(actual=both.actual_n), both.q50_n, regs[fy]))
            a, s, avc, cr = pool([both.actual * 0.25, both.actual_n * 0.25], [both.q50 * 0.25, both.q50_n * 0.25],
                                 [np.full(len(both), 100.0)] * 2, [decide.CONTRACT_RATE] * 2)
            pooled = settle(a, s, avc, cr, regs[fy]).loss_rs.sum() / both.day.nunique() * 365 / 1e5
            arow.append({"FY": fy_label(fy), "two plants alone": round(alone, 1), "pooled via QCA": round(pooled, 1),
                         "saved %": round((1 - pooled / alone) * 100, 1)})
        corr = float(np.corrcoef(both.actual - both.q50, both.actual_n - both.q50_n)[0, 1])
        head["pooling"] = arow
        head["pooling_error_corr"] = round(corr, 2)
        md += ["## 6. Aggregation with a neighbouring 100 MW plant (Note-2 pooling)", "",
               "Neighbour modelled 25 km south-west (a different Open-Meteo grid cell; `scripts/neighbour.py`), "
               f"GBM median schedules, {both.day.nunique()} out-of-sample days. "
               f"Correlation of the two plants' forecast errors: {corr:.2f}. "
               "A real pooling-station neighbour is closer, so its errors are more alike and the saving smaller: "
               "read this as an upper bound.", "", pd.DataFrame(arow).to_markdown(index=False), ""]
        fig, ax = charts.figure()
        x = np.arange(len(arow))
        for i, (col, lab) in enumerate([("two plants alone", "Each plant settled alone"),
                                        ("pooled via QCA", "Pooled through a QCA")]):
            vals = [r[col] for r in arow]
            ax.bar(x + (i - 0.5) * 0.38, vals, width=0.34, color=charts.SERIES[i], label=lab)
        for k, r in enumerate(arow):
            ax.annotate(f"−{r['saved %']:.0f}%", (x[k] + 0.19, r["pooled via QCA"]), xytext=(0, 4),
                        textcoords="offset points", ha="center", fontsize=9, color=charts.INK_2)
        ax.set_xticks(x, [r["FY"] for r in arow])
        ax.set_ylabel("₹ lakh per year, both plants", color=charts.INK_2)
        ax.legend(frameon=False, fontsize=9, loc="upper left")
        charts.title(ax, "Pooling with a neighbour nets out part of the error",
                     f"Two 100 MW plants 25 km apart, error correlation {corr:.2f}; an upper bound")
        charts.save(fig, FIG / "aggregation.png")

    # 7. sensitivity -------------------------------------------------------------------------
    sens = []
    for name, df, reg in [
        ("Base: final X path, lead 2", r_test, None),
        ("Draft X path (80/60/40/20)", r_test, "draft"),
        ("Lead 1 forecasts (optimistic bound)", lead1[lead1.day >= SELECT_END].reset_index(drop=True), None),
    ]:
        rg = regimes(reg or "final")
        sens.append({"case": name} | {fy_label(fy): decide.annual_loss_lakh(df, df.q50, rg[fy]) for fy in FYS})
    lit = decide.annual_loss_lakh(r_test, r_test.q50, CERC_2014)
    sens.append({"case": "Litigation succeeds: DSM 2014 (15% band), every year"} | {fy_label(fy): lit for fy in FYS})
    hi_rate = decide.CONTRACT_RANGE[1] / decide.CONTRACT_RATE
    sens.append({"case": f"Contract rate ₹{decide.CONTRACT_RANGE[1]}/kWh"} | {k: v * hi_rate for k, v in sens[0].items() if k != "case"})
    sens = pd.DataFrame(sens).round(1)
    head["litigation_loss_lakh"] = round(lit, 1)
    md += ["## 7. Sensitivity (GBM median schedule, ₹ lakh/yr)", "", sens.to_markdown(index=False), "",
           "Loss is linear in the contract rate. The Third Amendment (Reg 8(4A)) does not apply to this plant; "
           "a plant bid from 2027 would face General Seller charges instead.", ""]
    fig, ax = charts.figure()
    fx = [fy_label(fy) for fy in FYS]
    for i, row in sens.iterrows():
        ax.plot(range(len(FYS)), row[fx].astype(float), marker="o", ms=4, lw=2.5 if i == 0 else 1.5,
                color=charts.SERIES[i], label=row.case)
    ax.set_xticks(range(len(FYS)), fx)
    ax.set_ylabel("₹ lakh per year", color=charts.INK_2)
    ax.set_ylim(bottom=0)
    ax.legend(frameon=False, fontsize=8, loc="upper left")
    charts.title(ax, "The court case moves the answer more than any other setting",
                 "Annual loss with the GBM median schedule under each alternative")
    charts.save(fig, FIG / "sensitivity.png")

    (OUT / "headline.json").write_text(json.dumps(head, indent=2, default=float) + "\n")
    (ROOT / "docs" / "ANALYSIS.md").write_text("\n".join(md))
    print("\n".join(md))
