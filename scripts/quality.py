"""Rebuild the DuckDB catalogue and write docs/DATA_QUALITY.md.

For every source: row count, date range, missing timestamps on the regular
grid, and runs of nulls per variable. Nothing is filled here; gaps are only
logged, and how each one is handled is decided where the data is used.

    uv run python scripts/quality.py
"""

from datetime import datetime

import duckdb
import pandas as pd

from solarschedule import openmeteo as om
from solarschedule.store import DB_PATH, ROOT, build_db, find_gaps, find_null_runs

OUT = ROOT / "docs" / "DATA_QUALITY.md"
MAX_RUNS_LISTED = 10


def section(title: str, df: pd.DataFrame, cols: list[str], freq: str) -> list[str]:
    lines = [f"### {title}", ""]
    if df.empty:
        return lines + ["No data.", ""]
    lines.append(
        f"{len(df):,} rows, {df.time_ist.min():%Y-%m-%d %H:%M} to {df.time_ist.max():%Y-%m-%d %H:%M} IST."
    )
    dup = df.time_ist.duplicated().sum()
    if dup:
        lines.append(f"**{dup} duplicate timestamps.**")
    gaps = find_gaps(df.time_ist, freq)
    lines.append(f"Missing timestamps: {int(gaps.n_missing.sum()) if len(gaps) else 0}.")
    if len(gaps):
        listed = "; ".join(f"{s:%Y-%m-%d %H:%M} ({n})" for s, n in zip(gaps.start[:MAX_RUNS_LISTED], gaps.n_missing[:MAX_RUNS_LISTED]))
        more = f"; +{len(gaps) - MAX_RUNS_LISTED} more runs" if len(gaps) > MAX_RUNS_LISTED else ""
        lines.append(f"Missing runs (start, steps): {listed}{more}.")
    lines += ["", "| Variable | Null steps | Runs | Longest run | Listed runs (start, steps) |", "|---|---|---|---|---|"]
    for c in cols:
        r = find_null_runs(df, [c], freq)
        if r.empty:
            lines.append(f"| {c} | 0 | 0 | 0 | |")
            continue
        listed = "; ".join(f"{s:%Y-%m-%d %H:%M} ({n})" for s, n in zip(r.start[:MAX_RUNS_LISTED], r.n_missing[:MAX_RUNS_LISTED]))
        more = f"; +{len(r) - MAX_RUNS_LISTED} more" if len(r) > MAX_RUNS_LISTED else ""
        lines.append(f"| {c} | {int(r.n_missing.sum())} | {len(r)} | {int(r.n_missing.max())} | {listed}{more} |")
    return lines + [""]


def main() -> None:
    views = build_db()
    con = duckdb.connect(str(DB_PATH), read_only=True)
    q = lambda sql: con.execute(sql).df()  # noqa: E731

    out = [
        "# Data quality",
        "",
        f"Generated by `scripts/quality.py` on {datetime.now():%Y-%m-%d %H:%M} IST. Do not edit by hand.",
        "Times are naive IST. A 'run' is a block of consecutive missing steps.",
        "",
        f"DuckDB views: {', '.join(f'`{v}`' for v in views)}.",
        "",
        "## Open-Meteo",
        "",
    ]
    if "archive_hourly" in views:
        out += section("Archive (reanalysis), hourly", q("SELECT * FROM archive_hourly ORDER BY time_ist"), om.VARS, "1h")
    if "hist15" in views:
        out += section("Historical forecast, 15-minute", q("SELECT * FROM hist15 ORDER BY time_ist"), om.VARS_15, "15min")
    if "dayahead_hourly" in views:
        da = q("SELECT * FROM dayahead_hourly ORDER BY model, lead_days, time_ist")
        for (m, d), g in da.groupby(["model", "lead_days"]):
            out += section(f"Day-ahead `{m}`, lead {d} day(s), hourly", g, om.VARS, "1h")

    if "kaggle_generation" in views:
        out += ["## Kaggle plants (15-minute)", ""]
        gen = q("SELECT * FROM kaggle_generation")
        wx = q("SELECT * FROM kaggle_weather")
        for plant, g in gen.groupby("plant"):
            plant_level = g.groupby("time_ist", as_index=False)[["dc_power", "ac_power"]].sum()
            out += section(f"Plant {plant} generation (summed over {g.source_key.nunique()} inverters)", plant_level, ["ac_power"], "15min")
            per_ts = g.groupby("time_ist").source_key.nunique()
            short = per_ts[per_ts < g.source_key.nunique()]
            out += [f"Timestamps with fewer than all inverters reporting: {len(short)} of {len(per_ts)}.", ""]
        for plant, g in wx.groupby("plant"):
            out += section(f"Plant {plant} weather sensor", g, ["ambient_temperature", "module_temperature", "irradiation"], "15min")

    OUT.write_text("\n".join(out))
    print(f"wrote {OUT.relative_to(ROOT)}  ({len(views)} views)")


if __name__ == "__main__":
    main()
