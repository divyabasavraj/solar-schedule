"""Milestone 3: calibrate the plant model on Kaggle Plant 1, then model
15-minute "actual" output of the 100 MW Pavagada plant from 2023.

    uv run python scripts/plant_model.py

Writes
  data/derived/plant_params.json    fitted parameters
  data/derived/actual_15.parquet    time_ist, poa, mw (from hist15), mw_era5
  docs/PLANT_CALIBRATION.md         numbers (generated, do not edit)

Calibration is scored out of sample: fit on the first 24 days, test on the
last 10. The parameters saved are refit on all 34 days.
"""

import json

import numpy as np
import pandas as pd

from solarschedule import plant
from solarschedule.store import DATA, RAW, ROOT, write

OUT = DATA / "derived"
TRAIN_DAYS = 24


def score(pred: pd.Series, obs: pd.Series, cap: float) -> dict:
    e = (pred - obs) / cap * 100
    return {
        "mae_pct_cap": round(float(e.abs().mean()), 2),
        "rmse_pct_cap": round(float(np.sqrt((e**2).mean())), 2),
        "bias_pct_cap": round(float(e.mean()), 2),
        "energy_err_pct": round(float((pred.sum() / obs.sum() - 1) * 100), 2),
    }


def kaggle_scores(gen, weather) -> list[dict]:
    rows = []
    for p in (1, 2):
        df = plant.kaggle_frame(gen, weather, p)
        cut = df.time_ist.min().normalize() + pd.Timedelta(days=TRAIN_DAYS)
        train, test = df[df.time_ist < cut], df[(df.time_ist >= cut) & (df.g > 0)]
        prm = plant.calibrate(train)
        for measured in (True, False):
            pred = plant.predict_kaggle(test, prm, measured)
            rows.append(
                {"plant": p, "module_temp": "measured" if measured else "modelled",
                 "test_rows": len(test)}
                | {k: round(v, 4) for k, v in prm.as_dict().items()}
                | score(pred, test.ac_kw, prm.clip_kw)
            )
    return rows


def load(kind: str) -> pd.DataFrame:
    files = sorted((RAW / "openmeteo" / kind).glob("*.parquet"))
    return pd.concat([pd.read_parquet(f) for f in files], ignore_index=True)


def main() -> None:
    gen = pd.read_parquet(RAW / "kaggle" / "generation.parquet")
    weather = pd.read_parquet(RAW / "kaggle" / "weather.parquet")
    scores = pd.DataFrame(kaggle_scores(gen, weather))
    prm = plant.calibrate(plant.kaggle_frame(gen, weather, 1))
    (OUT).mkdir(parents=True, exist_ok=True)
    (OUT / "plant_params.json").write_text(json.dumps(
        prm.as_dict() | {"capacity_mw": plant.CAPACITY_MW, "tilt": plant.TILT,
                         "azimuth": plant.AZIMUTH, "source": "Kaggle Plant 1, all 34 days"},
        indent=2) + "\n")

    h15 = load("hist15")
    era5 = plant.to_15min(load("archive").query("time_ist >= '2023-01-01'"))
    actual = h15[["time_ist"]].assign(poa=plant.poa(h15, "15min"), mw=plant.ac_mw(h15, prm))
    actual = actual.merge(
        era5[["time_ist"]].assign(mw_era5=plant.ac_mw(era5, prm)), on="time_ist", how="left")
    write(actual.round({"poa": 2, "mw": 4, "mw_era5": 4}), OUT / "actual_15.parquet")

    a = actual.set_index("time_ist")
    cf = (a[["mw", "mw_era5"]].groupby(a.index.year).mean() / plant.CAPACITY_MW * 100).round(1)
    both = a[["mw", "mw_era5"]].dropna()
    both = both[(both.mw > 0) | (both.mw_era5 > 0)]
    agree = {
        "corr": round(float(both.corr().iloc[0, 1]), 3),
        "mae_pct_cap": round(float((both.mw - both.mw_era5).abs().mean()), 2),
    }

    fmt = lambda df: df.to_markdown(index=False)  # noqa: E731
    keep = ["plant", "module_temp", "a_kw", "clip_kw", "dc_ac", "gamma", "u",
            "mae_pct_cap", "rmse_pct_cap", "bias_pct_cap", "energy_err_pct"]
    md = f"""# Plant model calibration (generated by scripts/plant_model.py; do not edit)

Method and choices: `docs/PLANT.md`.

## Out-of-sample fit on the Kaggle plants
Fit on the first {TRAIN_DAYS} days, scored on daylight rows of the last 10 (per inverter, as % of the fitted clip level).

{fmt(scores[keep])}

## Parameters used (Kaggle Plant 1, refit on all 34 days)
{fmt(pd.DataFrame([prm.as_dict()]).round(4))}

## Modelled Pavagada output, 100 MW AC
Capacity factor (%, AC) by year, from the two "what happened" sources:

{fmt(cf.reset_index(names="year").dropna())}

hist15 vs ERA5 (15-min, daylight): correlation {agree['corr']}, mean absolute difference {agree['mae_pct_cap']}% of capacity.
Rows: {len(actual):,}, {actual.time_ist.min()} to {actual.time_ist.max()}; null mw: {int(actual.mw.isna().sum())}.
"""
    (ROOT / "docs" / "PLANT_CALIBRATION.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
